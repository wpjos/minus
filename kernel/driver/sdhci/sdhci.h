#ifndef __SDHCI_H__
#define __SDHCI_H__

#include "types.h"

/*
 * Standard SDHCI register offsets
 */
#define SDHCI_DMA_ADDRESS	0x00
#define SDHCI_BLOCK_SIZE	0x04
#define SDHCI_BLOCK_COUNT	0x06
#define SDHCI_ARGUMENT		0x08
#define SDHCI_TRANSFER_MODE	0x0c
#define SDHCI_COMMAND		0x0e
#define SDHCI_RESPONSE		0x10	/* 4 x 32-bit */
#define SDHCI_BUFFER		0x20
#define SDHCI_PRESENT_STATE	0x24
#define SDHCI_HOST_CONTROL	0x28
#define SDHCI_POWER_CONTROL	0x29
#define SDHCI_BLOCK_GAP_CONTROL	0x2a
#define SDHCI_WAKE_UP_CONTROL	0x2b
#define SDHCI_CLOCK_CONTROL	0x2c
#define SDHCI_TIMEOUT_CONTROL	0x2e
#define SDHCI_SOFTWARE_RESET	0x2f
#define SDHCI_INT_STATUS	0x30
#define SDHCI_INT_ENABLE	0x34
#define SDHCI_SIGNAL_ENABLE	0x38
#define SDHCI_ACMD12_ERR	0x3c
#define SDHCI_HOST_CONTROL2	0x3e
#define SDHCI_CAPS		0x40
#define SDHCI_CAPS_1		0x44
#define SDHCI_MAX_CURRENT	0x48
#define SDHCI_SET_ACMD12_ERROR	0x50
#define SDHCI_SET_INT_ERROR	0x52
#define SDHCI_ADMA_ERROR	0x54
#define SDHCI_ADMA_ADDRESS	0x58
#define SDHCI_ADMA_ADDRESS_HI	0x5c
#define SDHCI_PRESET_VALUE	0x60
#define SDHCI_SLOT_INT_STATUS	0xfc
#define SDHCI_HOST_VERSION	0xfe

/*
 * Command register bits
 */
#define SDHCI_CMD_RESP_MASK	0x03
#define SDHCI_CMD_CRC		0x08
#define SDHCI_CMD_INDEX		0x10
#define SDHCI_CMD_DATA		0x20
#define SDHCI_CMD_ABORTCMD	0xc0

#define SDHCI_CMD_RESP_NONE	0x00
#define SDHCI_CMD_RESP_LONG	0x01
#define SDHCI_CMD_RESP_SHORT	0x02
#define SDHCI_CMD_RESP_SHORT_BUSY 0x03

/*
 * Transfer mode bits
 */
#define SDHCI_TRNS_BLK_CNT_EN	0x02
#define SDHCI_TRNS_DMA		0x01
#define SDHCI_TRNS_MULTI	0x20
#define SDHCI_TRNS_READ		0x10
#define SDHCI_TRNS_AUTO_CMD12	0x04

/*
 * Present state bits
 */
#define SDHCI_CMD_INHIBIT	0x00000001
#define SDHCI_DAT_INHIBIT	0x00000002
#define SDHCI_DAT_ACTIVE	0x00000004
#define SDHCI_DOING_WRITE	0x00000100
#define SDHCI_DOING_READ	0x00000200
#define SDHCI_SPACE_AVAILABLE	0x00000400
#define SDHCI_DATA_AVAILABLE	0x00000800
#define SDHCI_CARD_PRESENT	0x00010000
#define SDHCI_CARD_STATE_STABLE	0x00020000
#define SDHCI_WRITE_PROTECT	0x00080000

/*
 * Host control bits
 */
#define SDHCI_CTRL_LED		0x01
#define SDHCI_CTRL_4BITBUS	0x02
#define SDHCI_CTRL_HISPD	0x04
#define SDHCI_CTRL_DMA_MASK	0x18
#define SDHCI_CTRL_8BITBUS	0x20

/*
 * Host control2 bits
 */
#define SDHCI_CTRL2_UHS_MASK	0x0007
#define SDHCI_CTRL2_SDR12	0x0000
#define SDHCI_CTRL2_SDR25	0x0001
#define SDHCI_CTRL2_SDR50	0x0002
#define SDHCI_CTRL2_SDR104	0x0003
#define SDHCI_CTRL2_DDR50	0x0004
#define SDHCI_CTRL2_HS400	0x0005
#define SDHCI_CTRL2_VDD_180	0x0008
#define SDHCI_CTRL2_DRV_TYPE_MASK 0x0030
#define SDHCI_CTRL2_EXEC_TUNING	0x0040
#define SDHCI_CTRL2_TUNED_CLK	0x0080
#define SDHCI_CTRL2_PRESET_VAL_ENABLE	0x8000

/*
 * Power control bits
 */
#define SDHCI_POWER_ON		0x01
#define SDHCI_POWER_180		0x0a
#define SDHCI_POWER_300		0x0c
#define SDHCI_POWER_330		0x0e
#define SDHCI_POWER_MASK	0x0f

/*
 * Clock control bits
 */
#define SDHCI_DIVIDER_SHIFT	8
#define SDHCI_DIVIDER_HI_SHIFT	6
#define SDHCI_CLOCK_CARD_EN	0x0004
#define SDHCI_CLOCK_INT_STABLE	0x0002
#define SDHCI_CLOCK_INT_EN	0x0001

/*
 * Software reset bits
 */
#define SDHCI_RESET_ALL		0x01
#define SDHCI_RESET_CMD		0x02
#define SDHCI_RESET_DATA	0x04

/*
 * Interrupt status bits
 */
#define SDHCI_INT_RESPONSE	0x00000001
#define SDHCI_INT_DATA_END	0x00000002
#define SDHCI_INT_BLK_GAP	0x00000004
#define SDHCI_INT_DMA_END	0x00000008
#define SDHCI_INT_SPACE_AVAIL	0x00000010
#define SDHCI_INT_DATA_AVAIL	0x00000020
#define SDHCI_INT_CARD_INSERT	0x00000040
#define SDHCI_INT_CARD_REMOVE	0x00000080
#define SDHCI_INT_CARD_INT	0x00000100
#define SDHCI_INT_ERROR		0x00008000
#define SDHCI_INT_TIMEOUT	0x00010000
#define SDHCI_INT_CRC		0x00020000
#define SDHCI_INT_END_BIT	0x00040000
#define SDHCI_INT_INDEX		0x00080000
#define SDHCI_INT_DATA_TIMEOUT	0x00100000
#define SDHCI_INT_DATA_CRC	0x00200000
#define SDHCI_INT_DATA_END_BIT	0x00400000
#define SDHCI_INT_BUS_POWER	0x00800000
#define SDHCI_INT_ACMD12ERR	0x01000000
#define SDHCI_INT_ADMA_ERROR	0x02000000

#define SDHCI_INT_NORMAL_MASK	0x00007fff
#define SDHCI_INT_ERROR_MASK	0xffff8000

#define SDHCI_INT_CMD_MASK	(SDHCI_INT_RESPONSE | SDHCI_INT_TIMEOUT | \
				 SDHCI_INT_CRC | SDHCI_INT_END_BIT | SDHCI_INT_INDEX)
#define SDHCI_INT_DATA_MASK	(SDHCI_INT_DATA_END | SDHCI_INT_DMA_END | \
				 SDHCI_INT_DATA_AVAIL | SDHCI_INT_SPACE_AVAIL | \
				 SDHCI_INT_DATA_TIMEOUT | SDHCI_INT_DATA_CRC | \
				 SDHCI_INT_DATA_END_BIT | SDHCI_INT_ADMA_ERROR)
#define SDHCI_INT_ALL_MASK	((uint32_t)0xffffffff)

/*
 * Caps bits
 */
#define SDHCI_CAN_VDD_330	0x01000000
#define SDHCI_CAN_VDD_300	0x02000000
#define SDHCI_CAN_VDD_180	0x04000000
#define SDHCI_CAN_64BIT_V4	0x08000000

#define SDHCI_CLOCK_BASE_MASK	0x00003f00
#define SDHCI_CLOCK_BASE_SHIFT	8
#define SDHCI_MAX_BLOCK_MASK	0x00030000
#define SDHCI_MAX_BLOCK_SHIFT	16
#define SDHCI_TIMEOUT_CLK_MASK	0x0000003f
#define SDHCI_TIMEOUT_CLK_SHIFT 0
#define SDHCI_TIMEOUT_CLK_UNIT	0x00000080

#endif /* __SDHCI_H__ */
